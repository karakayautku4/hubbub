import SwiftUI
import AppKit

/// Session export: Markdown summary (metadata only — never message content or prompts), stage PNG, share card.
@MainActor
enum SessionExport {
    // MARK: Markdown

    nonisolated static func markdown(session s: SessionInfo, providerName: String? = nil) -> String {
        func esc(_ t: String) -> String {
            t.replacingOccurrences(of: "\n", with: " ").replacingOccurrences(of: "|", with: "\\|")
        }
        func dur(_ x: TimeInterval) -> String {
            let n = max(0, Int(x))
            return n >= 3600 ? "\(n / 3600)h \(n % 3600 / 60)m" : n >= 60 ? "\(n / 60)m \(n % 60)s" : "\(n)s"
        }
        let start = s.startedAt ?? s.lastEvent
        var models = Set([s.model].filter { !$0.isEmpty })
        s.subagents.forEach { if !$0.model.isEmpty { models.insert($0.model) } }

        var o = "# \(esc(s.name))\n\n"
        o += "- **Provider:** \(providerName ?? s.provider)\n"
        o += "- **Started:** \(ISO8601DateFormatter().string(from: start))\n"
        o += "- **Duration:** \(dur(min(s.activeSeconds ?? SessionRecord.unknownActiveCap, max(0, s.lastEvent.timeIntervalSince(start)))))\n"
        o += "- **Models:** \(models.isEmpty ? "?" : models.sorted().joined(separator: ", "))\n"
        o += "- **Tokens:** \(s.inputTokens.formatted()) in / \(s.outputTokens.formatted()) out\n"
        o += "- **Context:** \(Int(s.contextFraction * 100))% (\(s.contextTokens.formatted()) / \(s.contextLimit.formatted()) tokens)\n"
        o += "- **Cost:** \(String(format: "%.1f", s.costCredits)) credits\n"
        o += "- **Tool calls:** \(s.toolCalls) (\(s.failures) failed, \(Int(s.successRate * 100))% ok)\n\n"

        o += "## Sub-agents\n\n"
        if s.subagents.isEmpty { o += "_None_\n\n" }
        else {
            o += "| Agent | Model | Calls | Failed | Success | Duration |\n|---|---|---:|---:|---:|---:|\n"
            for a in s.subagents {
                o += "| \(esc(a.displayName)) | \(esc(a.model)) | \(a.toolCalls) | \(a.failures) | \(Int(a.successRate * 100))% | \(dur(Date().timeIntervalSince(a.startedAt))) |\n"
            }
            o += "\n"
        }

        o += "## Failures\n\n"
        o += s.failures > 0 ? "\(s.failures) failure(s) recorded.\n\n" : "_None_\n\n"
        o += "---\n_Generated by Hubbub. Contains metadata only (no prompts or messages)._\n"
        return o
    }

    static func saveMarkdown(_ s: SessionInfo) -> String {
        let md = markdown(session: s, providerName: ProviderRegistry.shared.name(for: s.provider))
        let p = NSSavePanel()
        p.nameFieldStringValue = "\(slug(s.name)).md"
        p.allowedContentTypes = [.plainText]
        guard HotkeyManager.runPanel(p) == .OK, let url = p.url else { return "" }
        do { try md.write(to: url, atomically: true, encoding: .utf8); return "Saved \(url.lastPathComponent)" }
        catch { return "Could not save" }
    }

    static func copyMarkdown(_ s: SessionInfo) -> String {
        let md = markdown(session: s, providerName: ProviderRegistry.shared.name(for: s.provider))
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(md, forType: .string)
        return "Markdown copied"
    }

    // MARK: Images

    static func png(_ img: NSImage) -> Data? {
        guard let tiff = img.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    private static func savePNG(_ img: NSImage?, name: String) -> String {
        guard let img, let data = png(img) else { return "Nothing to export" }
        let p = NSSavePanel()
        p.nameFieldStringValue = name
        p.allowedContentTypes = [.png]
        guard HotkeyManager.runPanel(p) == .OK, let url = p.url else { return "" }
        do { try data.write(to: url); return "Saved \(url.lastPathComponent)" } catch { return "Could not save" }
    }

    static func saveStagePNG(_ s: SessionInfo) -> String {
        // Offscreen render uses the scene as configured for the current theme (background included).
        savePNG(Stage.current?.snapshot(width: 1272, height: 716), name: "\(slug(s.name))-stage.png")
    }

    static func saveShareCard(_ s: SessionInfo) -> String {
        let r = ImageRenderer(content: ShareCard(session: s, theme: Theme.resolve(UserDefaults.standard.string(forKey: "theme") ?? "")))
        r.scale = 1
        return savePNG(r.nsImage, name: "\(slug(s.name))-card.png")
    }

    private static func slug(_ t: String) -> String {
        let r = t.lowercased().map { $0.isLetter || $0.isNumber ? $0 : "-" }
        let s = String(r).split(separator: "-").joined(separator: "-")
        return s.isEmpty ? "session" : String(s.prefix(40))
    }

    // MARK: Self test

    /// `Hubbub --selftest-export`: synthetic session; verifies structure and that no message/prompt text leaks.
    static func selfTest() -> Bool {
        let secret = "SECRET_PROMPT_TEXT"
        let t0 = Date(timeIntervalSince1970: 1_700_000_000)
        var s = SessionInfo(id: "x", name: "Fix login bug", cwd: "/tmp/\(secret)", model: "claude-sonnet", lastEvent: t0.addingTimeInterval(600),
                            state: .idle, currentTool: nil, subagents: [], inputTokens: 1200, outputTokens: 300, toolCalls: 3)
        s.startedAt = t0; s.failures = 1; s.costCredits = 2.5; s.contextTokens = 90_000; s.contextLimit = 100_000; s.provider = "claude"
        s.lastError = secret
        s.recentCalls = [ToolCallRecord(id: "c1", time: t0, tool: "bash", detail: secret, status: .failed)]
        s.subagents = [SubAgent(id: "s1", name: "explore", displayName: "Explorer", model: "gpt-5", startedAt: t0.addingTimeInterval(15), toolCalls: 1)]
        let md = markdown(session: s, providerName: "Claude Code")
        let md2 = markdown(session: s)
        let checks: [(String, Bool)] = [
            ("no leak", !md.contains(secret) && !md2.contains(secret)),
            ("title", md.hasPrefix("# Fix login bug")),
            ("provider", md.contains("Claude Code")),
            ("models", md.contains("gpt-5") && md.contains("claude-sonnet")),
            ("sub table", md.contains("| Explorer | gpt-5 | 1 | 0 | 100% |")),
            ("failures", md.contains("1 failure(s) recorded")),
        ]
        for (n, ok) in checks { print("\(ok ? "PASS" : "FAIL") export: \(n)") }
        return checks.allSatisfy(\.1)
    }
}

struct ShareCard: View {
    let session: SessionInfo
    let theme: Theme

    var body: some View {
        ZStack {
            LinearGradient(colors: [Color(red: 0.10, green: 0.10, blue: 0.22), Color(red: 0.45, green: 0.12, blue: 0.45)], startPoint: .topLeading, endPoint: .bottomTrailing)
            VStack(alignment: .leading, spacing: 18) {
                HStack {
                    Text(theme.icon).font(.system(size: 84))
                    Spacer()
                    Text("Hubbub").font(.system(size: 40, weight: .heavy, design: .rounded)).foregroundStyle(.white.opacity(0.9))
                }
                Text(session.name).font(.system(size: 54, weight: .bold, design: .rounded)).foregroundStyle(.white).lineLimit(2)
                Text("\(ProviderRegistry.shared.name(for: session.provider)) · \(session.model.isEmpty ? "?" : session.model)")
                    .font(.system(size: 26)).foregroundStyle(.white.opacity(0.7))
                Spacer()
                HStack(spacing: 18) {
                    tile("Tool calls", "\(session.toolCalls)")
                    tile("Success", "\(Int(session.successRate * 100))%")
                    tile("Context", "\(Int(session.contextFraction * 100))%")
                    tile("Credits", String(format: "%.1f", session.costCredits))
                    tile("Tokens", compact(session.inputTokens + session.outputTokens))
                }
            }
            .padding(52)
        }
        .frame(width: 1200, height: 630)
    }

    private func tile(_ k: String, _ v: String) -> some View {
        VStack(alignment: .leading, spacing: 4) {
            Text(v).font(.system(size: 46, weight: .bold, design: .rounded)).foregroundStyle(.white)
            Text(k).font(.system(size: 20)).foregroundStyle(.white.opacity(0.65))
        }
        .padding(16).frame(maxWidth: .infinity, alignment: .leading)
        .background(RoundedRectangle(cornerRadius: 16).fill(.white.opacity(0.12)))
    }

    private func compact(_ n: Int) -> String { n >= 1_000_000 ? String(format: "%.1fM", Double(n) / 1e6) : n >= 1000 ? "\(n / 1000)k" : "\(n)" }
}

struct ExportMenu: View {
    let session: SessionInfo
    var onResult: (String) -> Void = { _ in }

    var body: some View {
        Menu("Export…") {
            Button("Save summary as Markdown…") { onResult(SessionExport.saveMarkdown(session)) }
            Button("Copy as Markdown") { onResult(SessionExport.copyMarkdown(session)) }
            Divider()
            Button("Save stage snapshot (PNG)…") { onResult(SessionExport.saveStagePNG(session)) }
            Button("Save share card (PNG)…") { onResult(SessionExport.saveShareCard(session)) }
        }
        .menuStyle(.borderlessButton).fixedSize()
    }
}
